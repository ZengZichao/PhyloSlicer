def test_cli():
    """Drive the four subcommands through ``phyloslicer.cli.main.main``.

    Each case writes into a throwaway directory, so the repository stays clean;
    the exit code is what the shell sees, and argparse usage errors surface as
    ``SystemExit(2)``.
    """
    import tempfile
    from contextlib import redirect_stderr, redirect_stdout
    from io import StringIO

    from phyloslicer.cli.main import main

    tree = str(DATA_DIR / "medium_tree.tre")
    sites = str(DATA_DIR / "medium_mat.csv")
    ptrees = str(DATA_DIR / "posterior_trees")

    def _cli(argv):
        out, err = StringIO(), StringIO()
        with redirect_stdout(out), redirect_stderr(err):
            try:
                rc = main(argv)
            except SystemExit as exc:  # argparse usage errors
                rc = exc.code if isinstance(exc.code, int) else 2
        return rc, out.getvalue(), err.getvalue()

