    def t02():
        tree = TreeArray.from_newick("((((A:1,B:1):1,C:2):1,D:3):1,E:4);")
        depths = tree.node_depths()
        assert depths[tree.root] == 0.0
        # E is at depth 4, A and B at depth 4
        assert abs(depths[0] - 4.0) < 1e-10  # A
        assert abs(depths[4] - 4.0) < 1e-10  # E
        return "depths correct"

    run_test("T-CORE-02", "Core", "Node depth computation", t02)

    def t03():
        tree = TreeArray.from_newick("((A:1,B:1):1,(C:1,D:1):1);")
