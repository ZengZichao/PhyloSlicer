@dataclass
class TestResult:
    test_id: str
    category: str
    description: str
    passed: bool
    elapsed_s: float
    error: str = ""
    details: str = ""


results: list[TestResult] = []


def run_test(test_id: str, category: str, desc: str, fn) -> TestResult:
    """Run a single test function and record the result."""
    t0 = time.perf_counter()
    try:
        detail = fn()
        elapsed = time.perf_counter() - t0
        r = TestResult(test_id, category, desc, True, elapsed, "", detail or "")
    except Exception as exc:
        elapsed = time.perf_counter() - t0
        tb = traceback.format_exc()
        r = TestResult(test_id, category, desc, False, elapsed, str(exc), tb)
    results.append(r)
    status = "PASS" if r.passed else "FAIL"
    print(f"  [{status}] {test_id}: {desc}" + (f" ({r.elapsed_s:.3f}s)" if r.passed else ""))
    if not r.passed:
        print(f"         Error: {r.error}")
    return r


